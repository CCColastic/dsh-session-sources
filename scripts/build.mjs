import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { Script } from 'node:vm';
const root = resolve(import.meta.dirname, '..');
const read = name => readFile(resolve(root, name), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const dictionaries = { zh: JSON.parse(await read('locale/zh.json')), en: JSON.parse(await read('locale/en.json')) };
const keys = dict => Object.keys(dict).sort().join('\n');
if (keys(dictionaries.zh) !== keys(dictionaries.en)) throw new Error('Locale keys differ');
if (dictionaries.zh.meta.title !== '会话资料' || dictionaries.en.meta.title !== 'Session Sources') throw new Error('Incorrect localized plugin title');
const css = await read('src/client.css');
for (const variable of css.matchAll(/var\((--[^,)]+)/g)) if (!variable[1].startsWith('--dsw-alias-')) throw new Error(`Unexpected theme variable ${variable[1]}`);
const source = await read('src/client.js');
if (/require\(['"]@deepseek-ai\//.test(source)) throw new Error('Client must not import internal host packages');
const output = source.replace('__SESSION_SOURCES_DICTS__', JSON.stringify(dictionaries)).replace('__SESSION_SOURCES_CSS__', JSON.stringify(css));
new Script(output, { filename: 'client.js' });
await writeFile(resolve(root, 'client.js'), output);
await mkdir(resolve(root, 'dist'), { recursive: true });
console.log(`Built ${pkg.name}@${pkg.version}; Chinese/English resources and client syntax verified.`);
